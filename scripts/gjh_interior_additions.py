"""Build the V11 interior additions: final asset ids, root names, hashes and the JavaScript registry.

Reads data/gjh-interior-additions.json and models/gjh-interior-additions/sources/*.glb (texture-free static
exports). Writes demos/corporate/gjh/v11/assets/GJH_<CAT>_<NNN>.glb and interior-additions-registry.js.
"""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/gjh-interior-additions.json'
ASSETS = ROOT / 'demos/corporate/gjh/v11/assets'
REGISTRY = ASSETS / 'interior-additions-registry.js'


def read_glb(data):
    if data[:4] != b'glTF' or struct.unpack('<I', data[4:8])[0] != 2 or data[16:20] != b'JSON':
        raise ValueError('Not a GLB 2.0 file')
    length = struct.unpack('<I', data[12:16])[0]
    return json.loads(data[20:20 + length]), data[20 + length:]


def write_glb(document, tail):
    text = json.dumps(document, separators=(',', ':')).encode()
    text += b' ' * (-len(text) % 4)
    total = 12 + 8 + len(text) + len(tail)
    return b'glTF' + struct.pack('<II', 2, total) + struct.pack('<I', len(text)) + b'JSON' + text + tail


def retarget(source_bytes, asset_id, source_name):
    document, tail = read_glb(source_bytes)
    scene = document['scenes'][document.get('scene', 0)]
    roots = [document['nodes'][i] for i in scene['nodes']]
    root = next((node for node in roots if node.get('name') == source_name), None)
    if root is None:
        raise ValueError(f'{source_name}: root node not found')
    root['name'] = asset_id
    root['extras'] = {**root.get('extras', {}), 'asset_id': asset_id}
    return write_glb(document, tail)


def outputs():
    spec = json.loads(DATA.read_text(encoding='utf-8'))
    files, entries = {}, {}
    for item in spec['assets']:
        source_path = ROOT / item['source']
        source = source_path.read_bytes()
        if hashlib.sha256(source).hexdigest() != item['source_sha256']:
            raise ValueError(f"{item['asset_id']}: source hash changed")
        asset_id = item['asset_id']
        glb = retarget(source, asset_id, source_path.stem)
        name = asset_id.replace('-', '_') + '.glb'
        files[ASSETS / name] = glb
        entries[item['kind']] = {
            'asset_id': asset_id, 'kind': item['kind'], 'version': '1.0.0', 'file': name,
            'sha256': hashlib.sha256(glb).hexdigest(), 'bytes': len(glb),
            'dimensions_m': item['dimensions_m'], 'capabilities': item['capabilities'],
            'priority': item['priority'], 'placed': item['placed'], 'label': item['label'],
            'source': item['source'], 'source_sha256': item['source_sha256'],
            'lod_policy': 'Single native-scale static mesh instanced per placement; simple-asset exemption. No distance LOD claim.',
            'uv_policy': 'No textures or baking; flat PBR materials only.',
            'collision_owner': 'V11 app-owned Rapier proxies; no visual collision nodes exported.',
            'rights': item['rights'],
        }
    body = json.dumps(entries, indent=2, ensure_ascii=False)
    files[REGISTRY] = ('// Generated by scripts/gjh_interior_additions.py; edit data/gjh-interior-additions.json.\n'
                       f'export const INTERIOR_ADDITIONS = Object.freeze({body});\n').encode('utf-8')
    return files


def build(check=False):
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_bytes() != content:
                raise ValueError(f'Regenerate interior additions: {path.relative_to(ROOT)}')
        else:
            path.write_bytes(content)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
