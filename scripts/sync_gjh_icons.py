"""Sync the V11 inline icon registry from an SVG-Icon-Studio worktree."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'demos/corporate/gjh/v11/assets/icons.js'
DEFAULT_STUDIO = Path.home() / 'Documents/GitHub/SVG-Icon-Studio'
ICON_IDS = (
    'arrow-down', 'arrow-down-right', 'arrow-left', 'arrow-right', 'arrow-up',
    'arrow-up-right', 'camera', 'cart', 'check', 'chevron-down', 'chevron-left',
    'chevron-right', 'chevron-up', 'close', 'door', 'download', 'eye',
    'help-circle', 'info', 'keyboard', 'lift', 'map-pin', 'menu', 'minus', 'mouse',
    'move', 'pick-up', 'plus', 'quality-inspection', 'refresh', 'run', 'search',
    'shopping-bag', 'sit', 'smartphone', 'theme',
)


def content(studio_root):
    catalog = studio_root / 'icons/catalog'
    # Decode bytes directly, rather than normalizing line endings: the registry
    # preserves each catalog file exactly, including its trailing newline.
    icons = {name: (catalog / f'{name}.svg').read_bytes().decode('utf-8')
             for name in ICON_IDS}
    data = json.dumps(icons, ensure_ascii=True, indent=2)
    return '''/* Generated by scripts/sync_gjh_icons.py from SVG-Icon-Studio; do not edit. */
export const registry = Object.freeze(''' + data + ''');

/** Create an inline Studio icon. Unlabelled icons are decorative. */
export function icon(name, { size = 24, label } = {}) {
  if (!Object.hasOwn(registry, name)) throw new Error(`Unknown icon: ${name}`);
  const parsed = new DOMParser().parseFromString(registry[name], 'image/svg+xml');
  const svg = document.importNode(parsed.documentElement, true);
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('focusable', 'false');
  if (label) {
    svg.removeAttribute('aria-hidden');
    svg.setAttribute('role', 'img');
    svg.setAttribute('aria-label', label);
  } else {
    svg.setAttribute('aria-hidden', 'true');
  }
  return svg;
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--studio-root', type=Path, default=DEFAULT_STUDIO,
                        help='SVG-Icon-Studio worktree (default: %(default)s)')
    parser.add_argument('--check', action='store_true', help='check for generated drift')
    args = parser.parse_args()
    try:
        expected = content(args.studio_root.expanduser())
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_bytes() != expected.encode('utf-8'):
                parser.exit(1, f'{OUTPUT.relative_to(ROOT)} is stale; run this script to sync it\n')
        else:
            OUTPUT.write_bytes(expected.encode('utf-8'))
    except (OSError, UnicodeError) as exc:
        parser.exit(1, f'Cannot sync Studio icons: {exc}\n')


if __name__ == '__main__':
    main()
