# Heals a page whose HTML is newer than the assets an older service worker still serves:
# ask the controlling worker for its build; activate on mismatch, but preserve unsaved input.
SW_GUARD = r"""(function () {
  var sw = navigator.serviceWorker;
  if (!sw || !sw.controller || !window.MessageChannel) return;
  var meta = document.querySelector('meta[name="pomelo-build"]');
  if (!meta) return;
  var want = meta.content, key = 'pomelo-v8-heal';
  function hasUnsavedInput() {
    if (document.querySelector('[data-dirty="true"]')) return true;
    return Array.from(document.querySelectorAll('form input, form textarea, form select')).some(function (field) {
      if (field.type === 'checkbox' || field.type === 'radio') return field.checked !== field.defaultChecked;
      if (field.tagName === 'SELECT') {
        var options = Array.from(field.options);
        if (field.multiple) return options.some(function (option) { return option.selected !== option.defaultSelected; });
        var initial = -1;
        options.forEach(function (option, index) { if (option.defaultSelected) initial = index; });
        if (initial < 0) initial = options.findIndex(function (option) {
          return !option.disabled && !(option.parentElement.tagName === 'OPTGROUP' && option.parentElement.disabled);
        });
        return field.selectedIndex !== initial;
      }
      return field.value !== field.defaultValue;
    });
  }
  var channel = new MessageChannel();
  channel.port1.onmessage = function (event) {
    if (!event.data || event.data.build === want) return;
    try {
      if (sessionStorage.getItem(key) === want) return;
      sessionStorage.setItem(key, want);
    } catch (error) { return; }
    sw.addEventListener('controllerchange', function () {
      if (hasUnsavedInput()) return;
      location.reload();
    }, {once: true});
    function go(worker) { worker.postMessage({type: 'SKIP_WAITING'}); }
    sw.getRegistration().then(function (registration) {
      if (!registration) return;
      return registration.update().catch(function () {}).then(function () {
        if (registration.waiting) return go(registration.waiting);
        var worker = registration.installing;
        if (worker) worker.addEventListener('statechange', function () {
          if (worker.state === 'installed') go(worker);
        });
      });
    }).catch(function () {});
  };
  sw.controller.postMessage({type: 'GET_BUILD'}, [channel.port2]);
})();"""


def components_page(ctx):
    """Every component and state on one review page, generated from the English page partials."""
    page = render("en", "index", ctx)
    body = (V8 / "src/components.html").read_text(encoding="utf-8")
    body = re.sub(r"\{\{t:([\w.-]+)\}\}", lambda m: html.escape(ctx["strings"]["en"][m.group(1)], quote=True), body)
    start, end = page.index('<main id="main" tabindex="-1">'), page.index("</main>")
    shell = page[:start] + '<main id="main" tabindex="-1">\n' + body + "\n" + page[end:]
    shell = shell.replace('data-page="index"', 'data-page="components"')
    shell = shell.replace("./", "../")
    shell = re.sub(r"\{\{icon:([\w-]+)\}\}", lambda m: icon_svg(ctx["icons"], m.group(1)), shell)
    return shell.replace('<meta name="robots" content="noindex,nofollow">',
                         '<meta name="robots" content="noindex,nofollow">\n<meta name="pomelo-design-review" content="components">')


def precache_list(outputs):
    files = [name for name in outputs if name.endswith(".html") and not name.startswith("design/")]
    files += ["assets/css/site.bundle.css", "assets/js/icons.generated.js", "manifest.webmanifest",
              "assets/img/pomelo-mark.svg", "assets/img/icon-192.png", "assets/img/icon-512.png"]
    files += sorted(p.relative_to(V8).as_posix() for p in (V8 / "assets/js").rglob("*.js") if p.name != "icons.generated.js")
    files += sorted(p.relative_to(V8).as_posix() for p in (V8 / "assets/img").glob("*-768.webp"))
    return sorted(set(files))


def service_worker(rel, files):
    template = (V8 / "src/sw.template.js").read_text(encoding="utf-8")
    return (template.replace("__BUILD__", json.dumps(rel["build"]))
            .replace("__VERSION__", json.dumps(rel["version"]))
            .replace("__PRECACHE__", json.dumps(files, indent=2)))


def manifest(ctx):
    strings = ctx["strings"]["en"]
    data = {"id": "./", "name": "Pomelo STEM · V8", "short_name": "Pomelo STEM", "lang": "en",
            "description": strings["meta.index.description"], "start_url": "./index.html", "scope": "./",
            "display": "standalone", "theme_color": "#1d5737", "background_color": "#fbf9f3",
            "icons": [{"src": "assets/img/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                      {"src": "assets/img/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                      {"src": "assets/img/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def outputs():
    rel = release()
    ctx = {"strings": dictionaries(), "icons": icons(), "release": rel, "theme_boot": THEME_BOOT, "sw_guard": SW_GUARD,
           "products": read_json(V8 / "src/data/products.json")}
    result = {}
    tokens = token_css()
    result["assets/css/tokens.css"] = tokens
    result["assets/css/site.bundle.css"] = css_bundle(tokens)
    result["assets/js/icons.generated.js"] = icons_js(ctx["icons"])
    for lang, info in LOCALES.items():
        folder = info["dir"] + "/" if info["dir"] else ""
        for page in PAGES + ("how-it-works",):
            result[f"{folder}{page}.html"] = render(lang, page, ctx)
    result["design/components.html"] = components_page(ctx)
    result["manifest.webmanifest"] = manifest(ctx)
    result["build-info.json"] = json.dumps({"version": rel["version"], "build": rel["build"]}, indent=2) + "\n"
    result["sw.js"] = service_worker(rel, precache_list(result))
    return result


