class PageStructure(HTMLParser):
    """Collect elements with their ancestors for generated shell contracts."""
    VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}

    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.elements = []
        self.stack = []
        self.feed(source)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        self.elements.append((tag, attrs, tuple(self.stack)))
        if tag not in self.VOID:
            self.stack.append((tag, attrs))

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, -1, -1):
            if self.stack[index][0] == tag:
                del self.stack[index:]
                break


def load_check_ssot():
    import importlib.util
    spec = importlib.util.spec_from_file_location("check_ssot", ROOT / "scripts/check_ssot.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_rules(result):
    errors = []
    strings = dictionaries()
    base = strings["en"]
    placeholder = re.compile(r"\{\w+\}")
    for lang, table in strings.items():
        missing, extra = set(base) - set(table), set(table) - set(base)
        if missing or extra:
            errors.append(f"i18n {lang}: missing {sorted(missing)} extra {sorted(extra)}")
        for key, value in table.items():
            if key in base and set(placeholder.findall(value)) != set(placeholder.findall(base[key])):
                errors.append(f"i18n {lang}: placeholder mismatch in {key}")
    # Hand-written CSS: no raw colours, sizes or durations outside tokens.
    ssot = load_check_ssot()
    duration = re.compile(r"(?<![\w-])\d*\.?\d+m?s\b")
    for path in sorted((V8 / "assets/css").rglob("*.css")):
        if path.name in ("tokens.css", "site.bundle.css"):
            continue
        source = path.read_text(encoding="utf-8")
        found = ssot.violations(path.relative_to(ROOT).as_posix(), source)
        errors += [f"SSOT literal: {item}" for item in found]
        for prop, value in re.findall(r"(?<![\w-])(transition|animation[\w-]*)\s*:\s*([^;}]+)", re.sub(r"/\*.*?\*/", "", source, flags=re.S)):
            if duration.search(re.sub(r"var\([^)]*\)", "", value)):
                errors.append(f"SSOT duration literal in {path.name}: {prop}: {value.strip()}")
        for prop in re.findall(r"(?<![\w-])transition(?:-property)?\s*:\s*([^;}]+)", source):
            for bad in ("width", "height", "top", "left", "margin"):
                if re.search(rf"(?<![\w-]){bad}(?![\w-])", prop):
                    errors.append(f"Motion must use transform/opacity only: {path.name}: {prop.strip()}")
        if ":hover" in source:
            for block in re.findall(r"([^{}]*:hover[^{}]*)\{", re.sub(r"/\*.*?\*/", "", source, flags=re.S)):
                pass
            if "@media (hover: hover)" not in source:
                errors.append(f"Hover styles must sit inside @media (hover: hover) and (pointer: fine): {path.name}")
    # Source markup: no hard-coded copy, raw SVG or native details/dialog.
    for path in sorted((V8 / "src").rglob("*.html")):
        source = path.read_text(encoding="utf-8")
        name = path.relative_to(V8).as_posix()
        if re.search(r"<svg\b", source):
            errors.append(f"Raw <svg> in {name}; use {{{{icon:name}}}}")
        if re.search(r"<(details|dialog)\b", source):
            errors.append(f"Native <details>/<dialog> in {name}; use the SSOT components")
        if name == "src/components.html":
            continue
        stripped = re.sub(r"<script\b.*?</script>", "", source, flags=re.S)
        stripped = re.sub(r"<!--.*?-->", "", stripped, flags=re.S)
        for attr in re.findall(r'\b(?:aria-label|alt|title|placeholder)="([^"]*)"', stripped):
            if attr and not re.fullmatch(r"(\{\{[^}]+\}\}\s*)+", attr):
                errors.append(f"Hard-coded attribute text in {name}: {attr}")
        text = re.sub(r"<[^>]+>", " ", stripped)
        while re.search(r"\{\{[^{}]+\}\}", text):
            text = re.sub(r"\{\{[^{}]+\}\}", " ", text)
        leftover = [w for w in text.split() if w not in ("·",)]
        if leftover:
            errors.append(f"Hard-coded text in {name}: {' '.join(leftover)[:80]}")
    # JS: no innerHTML with data, no window.confirm, strings come from i18n.
    for path in sorted((V8 / "assets/js").rglob("*.js")):
        source = path.read_text(encoding="utf-8")
        bare_confirm = re.search(r"(?<!function )(?<![\w.])confirm\(", source)
        imports_dialog = re.search(r"import \{[^}]*\bconfirm\b[^}]*\} from '[./]*(core/)?dialog\.js'", source) or path.name == "dialog.js"
        if "innerHTML" in source or re.search(r"window\.(confirm|alert|prompt)\(", source) or (bare_confirm and not imports_dialog):
            errors.append(f"Forbidden DOM API in {path.name}")
    # Version SSOT.
    rel = release()
    for name, text in result.items():
        if name.endswith(".html") and f'<meta name="pomelo-version" content="{rel["version"]}">' not in text:
            errors.append(f"Version meta mismatch in {name}")
    info = json.loads(result["build-info.json"])
    if info != {"version": rel["version"], "build": rel["build"]}:
        errors.append("build-info.json does not match release.json")
    if json.dumps(rel["build"]) not in result["sw.js"]:
        errors.append("sw.js build does not match release.json")
    # Every page links its three locales and has exactly one h1 and one banner.
    for name, text in result.items():
        if not name.endswith(".html"):
            continue
        elements = PageStructure(text).elements
        language_menus = [attrs for _, attrs, _ in elements if "data-lang-menu" in attrs]
        language_buttons = [attrs for tag, attrs, ancestors in elements if tag == "button"
                            and any("data-lang-menu" in parent for _, parent in ancestors)]
        top_buttons = [attrs for tag, attrs, _ in elements if tag == "button" and "data-back-to-top" in attrs]
        if len(language_menus) != 1 or len(language_buttons) != 1:
            errors.append(f"{name} must have exactly one [data-lang-menu] button")
        if len(top_buttons) != 1:
            errors.append(f"{name} must have exactly one back-to-top button")
        if name.startswith("design/"):
            continue
        if text.count("<h1") != 1 and "how-it-works" not in name:
            errors.append(f"{name} must have exactly one h1")
        if text.count('rel="alternate" hreflang=') != 3:
            errors.append(f"{name} must link three hreflang alternates")
    # Every referenced local file exists.
    for name, text in result.items():
        if not name.endswith(".html"):
            continue
        base_dir = (V8 / name).parent
        for ref in re.findall(r'(?:src|href)="([^"#?]+)', text):
            if ref.startswith(("http", "mailto:", "tel:")) or ref.endswith("/"):
                continue
            target = (base_dir / ref).resolve()
            generated = target.relative_to(V8.resolve()).as_posix() if str(target).startswith(str(V8.resolve())) else None
            if not target.exists() and generated not in result:
                errors.append(f"Broken link in {name}: {ref}")
    return errors


def build(check=False):
    result = outputs()
    errors = check_rules(result)
    stale = [name for name, text in result.items()
             if not (V8 / name).is_file() or (V8 / name).read_text(encoding="utf-8") != text]
    if check:
        if stale:
            errors.append("Regenerate Pomelo V8 outputs: " + ", ".join(stale))
    else:
        for name in stale:
            target = V8 / name
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(result[name])
    if errors:
        raise ValueError("Pomelo V8 check failed:\n- " + "\n- ".join(errors))
    return result


def runtime_files():
    """Files the published gallery must ship for V8 (relative to the repo root)."""
    names = set(outputs())
    names.update(p.relative_to(V8).as_posix() for p in (V8 / "assets/js").rglob("*.js"))
    names.update(p.relative_to(V8).as_posix() for p in (V8 / "assets/img").iterdir() if p.is_file())
    names.update({"release.json", "assets/thumbnail.webp", "screenshots/1440.png", "screenshots/768.png", "screenshots/390.png"})
    names.discard("assets/css/tokens.css")
    return sorted(Path("demos/corporate/pomelo-stem/v8") / name for name in names)


