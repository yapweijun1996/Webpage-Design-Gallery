"""Generate the V11 stylesheet in the same order as its source stylesheets."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    'assets/tokens.css',
    'assets/gjh-themes.css',
    'demos/corporate/gjh/v11/style.css',
    'assets/onboarding/onboarding.tokens.css',
    'assets/onboarding/onboarding.css',
    'demos/corporate/gjh/shared/interaction.css',
)
OUTPUT = ROOT / 'demos/corporate/gjh/v11/style.bundle.css'
ONBOARDING_IMPORT = "@import url('./onboarding.tokens.css');"


def content():
    parts = ['/* Generated by scripts/build_gjh_css.py; edit the source stylesheets. */']
    for name in SOURCES:
        css = (ROOT / name).read_text(encoding='utf-8')
        if name.endswith('/onboarding/onboarding.css'):
            if css.count(ONBOARDING_IMPORT) != 1:
                raise ValueError('The onboarding token import changed; review stylesheet ordering')
            css = css.replace(ONBOARDING_IMPORT, '', 1)
        if '@import' in css:
            raise ValueError(f'Unexpected CSS import requires review: {name}')
        if name != 'demos/corporate/gjh/v11/style.css' and 'url(' in css:
            raise ValueError(f'New relative CSS resource requires review: {name}')
        parts.append(f'/* Source: {name} */\n{css}')
    return '\n'.join(parts).rstrip() + '\n'


def build(check=False):
    expected = content()
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != expected:
            raise ValueError(f'Regenerate mall CSS: {OUTPUT.relative_to(ROOT)}')
    else:
        OUTPUT.write_text(expected, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    build(parser.parse_args().check)
