"""Build framework-neutral design tokens and the approved icon sprite."""

import argparse
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKEN_NAME = re.compile(r"[a-z][a-z0-9-]*\Z")


def read_tokens(root=ROOT):
    data = json.loads((root / "design-system/tokens.json").read_text())
    if not re.fullmatch(r"\d+\.\d+\.\d+", data["version"]):
        raise ValueError("Design system version must use major.minor.patch")
    tokens = {}
    for group in ("primitives", "semantics", "aliases"):
        for name, value in data[group].items():
            if not TOKEN_NAME.fullmatch(name) or name in tokens:
                raise ValueError(f"Invalid or duplicate token: {name}")
            if not isinstance(value, str) or any(char in value for char in ";{}<>"):
                raise ValueError(f"Invalid token value: {name}")
            tokens[name] = value
    for name in tokens:
        resolve_token(name, tokens)
    validate_contrast(tokens)
    return data, tokens


def resolve_token(name, tokens, seen=()):
    if name in seen:
        raise ValueError(f"Circular token reference: {name}")
    if name not in tokens:
        raise ValueError(f"Missing token reference: {name}")
    value = tokens[name]
    references = re.findall(r"var\(--([a-z0-9-]+)\)", value)
    for reference in references:
        value = value.replace(f"var(--{reference})", resolve_token(reference, tokens, (*seen, name)))
    return value


def contrast_ratio(first, second):
    def luminance(color):
        if not re.fullmatch(r"#[0-9a-fA-F]{6}", color):
            raise ValueError(f"Contrast pair must resolve to an opaque RGB token: {color}")
        channels = [int(color[index:index + 2], 16) / 255 for index in (1, 3, 5)]
        linear = [channel / 12.92 if channel <= .04045 else ((channel + .055) / 1.055) ** 2.4 for channel in channels]
        return sum(channel * weight for channel, weight in zip(linear, (.2126, .7152, .0722)))
    light, dark = sorted((luminance(first), luminance(second)), reverse=True)
    return (light + .05) / (dark + .05)


def validate_contrast(tokens):
    pairs = [(foreground, background, 4.5)
             for foreground in ("color-text", "color-text-muted", "color-action")
             for background in ("color-surface", "color-page")]
    pairs += [("color-on-action", "color-action", 4.5),
              ("color-on-action", "color-action-hover", 4.5),
              ("color-border-control", "color-surface", 3),
              ("color-focus", "color-surface", 3)]
    pairs += [(f"color-{status}", f"color-{status}-surface", 4.5)
              for status in ("success", "warning", "error")]
    for foreground, background, minimum in pairs:
        actual = contrast_ratio(resolve_token(foreground, tokens), resolve_token(background, tokens))
        if actual < minimum:
            raise ValueError(f"Token contrast below {minimum}: {foreground}/{background} = {actual:.2f}")


def render_tokens(root=ROOT):
    data, tokens = read_tokens(root)
    lines = ["/* Generated by scripts/build_design_system.py; edit design-system/tokens.json. */", f"/* Design System {data['version']} */", ":root {"]
    lines.extend(f"  --{name}: {value};" for name, value in tokens.items())
    return "\n".join([*lines, "}", ""])


def render_icons(root=ROOT):
    data = json.loads((root / "design-system/icons.json").read_text())
    tokens = json.loads((root / "design-system/tokens.json").read_text())
    if data["version"] != tokens["version"]:
        raise ValueError("Icon and token registry versions differ")
    known = {entry["id"] for entry in json.loads((root / "assets/icons-sources.json").read_text())["icons"]}
    lines = ['<svg xmlns="http://www.w3.org/2000/svg">', '  <!-- Generated by scripts/build_design_system.py; edit design-system/icons.json. -->']
    seen = set()
    for icon in data["icons"]:
        name = icon["id"]
        if name not in known or name in seen or not TOKEN_NAME.fullmatch(name):
            raise ValueError(f"Unknown or duplicate approved icon: {name}")
        seen.add(name)
        lines.append(f'  <symbol id="{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">')
        for shape in icon["shapes"]:
            tag = shape["tag"]
            allowed = {"path": {"d"}, "circle": {"cx", "cy", "r"}}
            if tag not in allowed or set(shape) - {"tag"} != allowed[tag]:
                raise ValueError(f"Invalid icon shape: {name}")
            attrs = " ".join(f'{key}="{html.escape(str(value), quote=True)}"' for key, value in shape.items() if key != "tag")
            lines.append(f"    <{tag} {attrs}/>")
        lines.append("  </symbol>")
    return "\n".join([*lines, "</svg>", ""])


def render_themes(root=ROOT):
    registry = json.loads((root / "design-system/themes.json").read_text())
    data, foundation = read_tokens(root)
    if registry["version"] != data["version"]:
        raise ValueError("Theme and token registry versions differ")
    lines = ["/* Generated by scripts/build_design_system.py; edit design-system/themes.json. */"]
    for version, theme in registry["themes"].items():
        if not re.fullmatch(r"v[1-9][0-9]*", version):
            raise ValueError(f"Invalid theme identity: {version}")
        groups = [(None, None, theme["tokens"])] + [(entry["condition"], entry.get("selector"), entry["tokens"]) for entry in theme["overrides"]]
        for condition, selector, values in groups:
            if condition and not re.fullmatch(r"@media\s*\((?:max|min)-width\s*:\s*\d+px\)", condition):
                raise ValueError(f"Invalid responsive theme condition: {condition}")
            merged = {**foundation, **theme["tokens"], **values}
            for name, value in values.items():
                if not TOKEN_NAME.fullmatch(name) or not isinstance(value, str) or any(char in value for char in ";{}<>"):
                    raise ValueError(f"Invalid theme token: {version}/{name}")
                resolve_token(name, merged)
            if condition:
                lines.append(condition + " {")
            scope = f'html[data-gjh-design="{version}"]'
            if selector:
                if any(char in selector for char in "{}<>;"):
                    raise ValueError(f"Invalid component theme selector: {selector}")
                scope = ", ".join(scope + " " + part.strip() for part in selector.split(","))
            lines.append(scope + " {")
            lines.extend(f"  --{name}: {value};" for name, value in values.items())
            lines.append("}")
            if condition:
                lines.append("}")
    return "\n".join([*lines, ""])


def outputs(root=ROOT):
    return {"assets/tokens.css": render_tokens(root), "assets/icons.svg": render_icons(root),
            "assets/gjh-themes.css": render_themes(root)}


def build(root=ROOT, check=False):
    stale = []
    for name, content in outputs(root).items():
        path = root / name
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise ValueError("Stale design-system artifacts: " + ", ".join(stale))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        build(check=args.check)
    except (ValueError, KeyError) as error:
        parser.exit(1, f"{error}\n")
    print("Design system checked" if args.check else "Design system built")
