"""Compile the programme to small synchronous projections used during warm-up."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'demos/corporate/gjh/v11/assets/interiors'
PLAN = ROOT / 'docs/gjh-v11-interior-program.json'


def project(shop):
    items = shop['items']
    focal = next(item for item in items if item['id'] == shop['focal'])
    manifest = json.loads((ASSETS / 'manifest.json').read_text())
    receipts = {entry['file']: entry['bytes'] for entry in manifest['assets']}
    def placement(item):
        return dict(position_m=item['xyz'], yaw_deg=item['yawDeg'], envelope_whd_m=item['size'])
    props = []
    for spec in shop['props']:
        for item in items:
            if item['socket'] == spec['socket']:
                props.append(dict(name=spec['name'], socket=spec['socket'], kind=spec['kind'],
                                  **placement(item)))
    colliders = []
    for item in items:
        if item['collision'] == 'kit':
            x, y, z = item['xyz']
            colliders.append(dict(center=[x, y+item['size'][1]/2, z], size=item['size'], yaw=item['yawDeg']))
    return dict(**{key:shop[key] for key in ('brand','style','concept','signature_family','frame','palette','floor','capture')},
                lighting=shop['lighting']['position_m'], accent_kelvin=shop['lighting']['accent_kelvin'],
                centreFixture=shop.get('centreFixture'), props=props, anchor=dict(asset_id=focal['modelId'], **placement(focal)),
                routes=shop['additional_clearance_segments'], pickups=[item['standing'] for item in items if item['socket']=='shelves'],
                colliders=colliders, files={tier:dict(file=file, bytes=receipts[file], tier=tier)
                    for tier,file in focal['lod'].items() if file.endswith('-'+tier+'.glb')})


def build(check=False):
    stores = json.loads(PLAN.read_text())['stores']
    layouts = {s['slot']: project(s) for s in stores}
    shelves = [dict(xyz=i['xyz'],size=i['size'],scale=i['scale'],standing=i['standing'])
               for i in stores[0]['items'] if i['socket']=='shelves']
    products = dict(origin=stores[0]['frame']['world_origin_m'], cabinets=shelves)
    seats = [item['xyz'] for item in stores[1]['items'] if item['socket']=='seats']
    baked = {i['lod']['low']: dict(**i['bakedPart'], xyz=i['xyz']) for store in stores
             for i in store['items'] if 'bakedPart' in i}
    fields = ('id','modelId','lod','zone','anchor','xyz','yawDeg','scale','size','collision','action','a11y','standing','reachDistance','targetId')
    actions = {shop['slot']: [{k:item[k] for k in fields if k in item} for item in shop['items']]
               for shop in stores}
    for name, symbol, data in [('action-layout','actionsBySlot',actions), ('baked-layout','bakedParts',baked), ('mili-seats','miliSeats',seats), ('layout','layouts',layouts), ('cabinet-layout','cabinetLayout',products)]:
        path = ASSETS / (name+'.js')
        content = '// Generated by scripts/gjh_interiors/build_layout.py from the interior programme.\n'
        content += 'export const '+symbol+' = '+json.dumps(data, ensure_ascii=False, separators=(',', ':'))+';\n'
        if check and path.read_text() != content:
            raise ValueError(f'Stale {path.name}')
        if not check:
            path.write_text(content)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    build(parser.parse_args().check)
