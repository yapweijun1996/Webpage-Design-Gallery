// Brace references use primitive group.name paths. Weight, leading and tracking each have their own scale.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const MODES = ['light', 'dark'];
const BRANDS = ['forest-gold', 'gjh-classic', 'cny-red-gold'];
const COLOR_ROLES = [
  'accent', 'action', 'action-active', 'action-hover', 'bg', 'border', 'border-strong',
  'danger', 'danger-bg', 'focus', 'info', 'info-bg', 'on-action', 'scrim', 'scrim-strong',
  'success', 'success-bg', 'surface', 'surface-2', 'surface-inverse', 'text', 'text-inverse',
  'text-muted', 'warning', 'warning-bg',
].map(role => `color-${role}`);
const GENERATED_COMMENT = 'Generated by swarm/design-system/build.js from tokens.json.';

function record(value, location) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${location} must be an object`);
  }
  return value;
}

function readPalettes(value, location) {
  const palettes = record(value, location);
  for (const mode of Object.keys(palettes)) {
    if (!MODES.includes(mode)) throw new Error(`Unknown theme ${location}.${mode}`);
  }
  return MODES.map(mode => {
    const modeLocation = `${location}.${mode}`;
    const roles = record(palettes[mode], modeLocation);
    for (const role of COLOR_ROLES) {
      if (!Object.hasOwn(roles, role)) {
        throw new Error(`${modeLocation} is missing required semantic role ${role}`);
      }
    }
    for (const role of Object.keys(roles)) {
      if (!COLOR_ROLES.includes(role)) throw new Error(`Unknown semantic role ${modeLocation}.${role}`);
    }
    return roles;
  });
}

function scaleName(group, name) {
  if (group === 'layout' || (group === 'loader' && name.startsWith('skeleton-'))) return name;
  return `${group}-${name}`;
}

function compile(source) {
  const primitives = new Map();
  const resolved = new Map();
  const defaults = new Map();

  function resolveValue(raw, location, chain = []) {
    if (typeof raw !== 'string' || !raw.trim() || /[;\r\n]/.test(raw)) {
      throw new Error(`${location} must be a nonempty CSS value on one line`);
    }
    const value = raw.replace(/\{([^{}]+)\}/g, (_, reference) => {
      if (!primitives.has(reference)) throw new Error(`Unknown token reference {${reference}} in ${location}`);
      if (chain.includes(reference)) {
        throw new Error(`Circular token reference: ${[...chain, reference].join(' -> ')}`);
      }
      if (!resolved.has(reference)) {
        resolved.set(reference, resolveValue(primitives.get(reference), `primitives.${reference}`, [...chain, reference]));
      }
      return resolved.get(reference);
    });
    if (/[{}]/.test(value)) throw new Error(`Malformed token reference in ${location}`);
    return value;
  }

  function addDefault(name, raw, location) {
    const property = `--sds-${name}`;
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`Invalid token name ${location}`);
    if (defaults.has(property) || COLOR_ROLES.includes(name)) throw new Error(`Duplicate CSS property ${property} in ${location}`);
    defaults.set(property, resolveValue(raw, location));
  }

  for (const [group, values] of Object.entries(record(source.primitives, 'primitives'))) {
    for (const [name, raw] of Object.entries(record(values, `primitives.${group}`))) {
      primitives.set(`${group}.${name}`, raw);
    }
  }
  for (const [reference, raw] of primitives) {
    addDefault(reference.replace('.', '-'), raw, `primitives.${reference}`);
  }
  for (const [group, values] of Object.entries(record(source.scale, 'scale'))) {
    for (const [name, raw] of Object.entries(record(values, `scale.${group}`))) {
      addDefault(scaleName(group, name), raw, `scale.${group}.${name}`);
    }
  }

  function palettePair(values, location) {
    return readPalettes(values, location).map((roles, index) => Object.fromEntries(
      COLOR_ROLES.map(role => [`--sds-${role}`, resolveValue(roles[role], `${location}.${MODES[index]}.${role}`)]),
    ));
  }

  const themes = palettePair(source.themes, 'themes');
  const brands = record(source.brands, 'brands');
  for (const brand of Object.keys(brands)) {
    if (!BRANDS.includes(brand)) throw new Error(`Unknown brand ${brand}`);
  }
  return {
    defaults: Object.fromEntries([...defaults.keys()].sort().map(property => [property, defaults.get(property)])),
    themes,
    brands: BRANDS.map(brand => [brand, palettePair(brands[brand], `brands.${brand}`)]),
  };
}

function cssRule(selectors, values) {
  const declarations = Object.entries(values).map(([property, value]) => `  ${property}: ${value};`);
  return [selectors.join(',\n') + ' {', ...declarations, '}'].join('\n');
}

function mediaRule(condition, rule) {
  return `@media (${condition}) {\n${rule.split('\n').map(line => `  ${line}`).join('\n')}\n}`;
}

function renderThemes(themes, brands, defaults) {
  const darkMedia = 'prefers-color-scheme: dark';
  const light = '[data-theme="light"]';
  const dark = '[data-theme="dark"]';
  const auto = '[data-theme="auto"]';
  const [lightValues, darkValues] = themes.map((values, index) => ({ ...values, 'color-scheme': MODES[index] }));
  const blocks = [
    cssRule([':root'], { 'color-scheme': 'light' }),
    cssRule([light, auto], lightValues),
    cssRule([dark], darkValues),
    mediaRule(darkMedia, cssRule([auto], darkValues)),
  ];
  for (const [brand, [brandLight, brandDark]] of brands) {
    const selector = `[data-brand="${brand}"]`;
    const lightValues = { ...brandLight, 'color-scheme': 'light' };
    const darkValues = { ...brandDark, 'color-scheme': 'dark' };
    blocks.push(
      cssRule([selector, selector + light, selector + auto], lightValues),
      cssRule([selector + dark], darkValues),
      mediaRule(darkMedia, cssRule([selector + auto], darkValues)),
    );
  }
  const reducedDurations = Object.fromEntries(Object.keys(defaults)
    .filter(property => property.startsWith('--sds-dur-'))
    .map(property => [property, '0.01ms']));
  blocks.push(mediaRule('prefers-reduced-motion: reduce', cssRule([':root'], reducedDurations)));
  return blocks.join('\n\n');
}

function renderReference(defaults, themes, brands) {
  const columns = ['Light', 'Dark'];
  const palettes = [...themes];
  for (const [brand, modes] of brands) {
    columns.push(`${brand} light`, `${brand} dark`);
    palettes.push(...modes);
  }
  const properties = [...Object.keys(defaults), ...Object.keys(themes[0])].sort();
  const cell = value => `\`${value.replaceAll('|', '\\|')}\``;
  const rows = properties.map(property => {
    const values = palettes.map(palette => cell(palette[property] ?? defaults[property]));
    return `| ${[cell(property), ...values].join(' | ')} |`;
  });
  return [
    '# Swarm Design System tokens',
    '',
    `<!-- ${GENERATED_COMMENT} -->`,
    '',
    'Edit `tokens.json` and run `node swarm/design-system/build.js` from the repository root.',
    'Auto uses the column for the system colour scheme and selected brand.',
    'With reduced motion enabled, every `--sds-dur-*` token is `0.01ms`.',
    '',
    `| Token | ${columns.join(' | ')} |`,
    `| ${['Token', ...columns].map(() => '---').join(' | ')} |`,
    ...rows,
    '',
  ].join('\n');
}

function outputs(source) {
  const { defaults, themes, brands } = compile(record(source, 'tokens.json'));
  const comment = `/* ${GENERATED_COMMENT} */\n\n`;
  return {
    'tokens.css': `${comment}${cssRule([':root'], { ...defaults, ...themes[0] })}\n`,
    'themes.css': `${comment}${renderThemes(themes, brands, defaults)}\n`,
    'TOKENS.md': renderReference(defaults, themes, brands),
  };
}

function diffSummary(filename, expected) {
  let actual;
  try {
    actual = fs.readFileSync(path.join(__dirname, filename), 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return `${filename} is missing`;
    throw error;
  }
  if (actual === expected) return '';

  const actualLines = actual.split('\n');
  const expectedLines = expected.split('\n');
  let line = 0;
  while (actualLines[line] === expectedLines[line]) line++;
  return [
    `${filename} differs at line ${line + 1}`,
    `  - ${actualLines[line] ?? '(end of file)'}`,
    `  + ${expectedLines[line] ?? '(end of file)'}`,
  ].join('\n');
}

function main(args) {
  const check = args.length === 1 && args[0] === '--check';
  if (args.length && !check) throw new Error('Usage: node swarm/design-system/build.js [--check]');

  const source = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
  const files = Object.entries(outputs(source));
  if (check) {
    const differences = files.map(([file, contents]) => diffSummary(file, contents)).filter(Boolean);
    if (differences.length) {
      throw new Error(`${differences.join('\n')}\nRun node swarm/design-system/build.js to regenerate SDS tokens.`);
    }
    console.log('SDS token outputs are in sync.');
    return;
  }

  for (const [file, contents] of files) fs.writeFileSync(path.join(__dirname, file), contents);
  console.log(`Generated ${files.map(([file]) => file).join(', ')}.`);
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`SDS token build failed: ${error.message}`);
    process.exitCode = 1;
  }
}
